#!/usr/bin/env node
/**
 * Converts public-domain Bible JSON (thiagobodruk/bible format) into small per-book files
 * the browser loads on demand (works for both the Mac server and the website):
 *
 *   public/bible/<id>/meta.json        { id, name, short, language, credit }
 *   public/bible/<id>/<book 0-65>.json [ ["verse 1", "verse 2", ...], ...chapters ]
 *   lib/verse-counts.js                verse count per chapter (longest of the bundled Bibles)
 *
 * Usage:
 *   node scripts/build-bibles.mjs <dir-with-downloaded-json>
 *
 * Download sources first (only public-domain texts are bundled):
 *   curl -LO https://raw.githubusercontent.com/thiagobodruk/bible/master/json/ko_krv.json
 *   curl -LO https://raw.githubusercontent.com/thiagobodruk/bible/master/json/en_webu.json
 *
 * ESV / NIV / 개역개정 are copyrighted and must NOT be bundled. ESV is supported
 * live through the official ESV API instead (set ESV_API_KEY).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "public", "bible");
const COUNTS_FILE = path.join(__dirname, "..", "lib", "verse-counts.js");

const SOURCES = [
  {
    file: "ko_krv.json",
    id: "krv",
    name: "개역한글 (Korean Revised Version, 1961)",
    short: "개역한글",
    language: "ko",
    credit: "개역한글판 (1961) — public domain.",
  },
  {
    file: "en_webu.json",
    id: "webu",
    name: "World English Bible (Updated)",
    short: "WEB",
    language: "en",
    credit: "World English Bible — public domain.",
  },
];

function cleanVerse(text, language) {
  let t = String(text ?? "");
  if (language === "en") {
    // Strip leftover footnote fragments such as: God " (Elohim). created
    t = t.replace(/\s*"\s*\([^)]*\)\.?/g, "");
    // Remove stray spaces before punctuation: "LORD ," -> "LORD,"
    t = t.replace(/\s+([,.;:!?’”])/g, "$1");
  }
  return t.replace(/\s+/g, " ").trim();
}

const srcDir = process.argv[2];
if (!srcDir) {
  console.error("Usage: node scripts/build-bibles.mjs <dir-with-downloaded-json>");
  process.exit(1);
}

const counts = [];

for (const src of SOURCES) {
  const inPath = path.join(srcDir, src.file);
  if (!fs.existsSync(inPath)) {
    console.warn(`skip ${src.file} (not found)`);
    continue;
  }
  const raw = JSON.parse(fs.readFileSync(inPath, "utf8").replace(/^\uFEFF/, ""));
  if (!Array.isArray(raw) || raw.length !== 66) {
    throw new Error(`${src.file}: expected 66 books, got ${raw?.length}`);
  }
  const dir = path.join(OUT_DIR, src.id);
  fs.mkdirSync(dir, { recursive: true });
  const { file, ...meta } = src;
  fs.writeFileSync(path.join(dir, "meta.json"), JSON.stringify(meta));
  raw.forEach((book, b) => {
    const chapters = book.chapters.map((ch) => ch.map((v) => cleanVerse(v, src.language)));
    fs.writeFileSync(path.join(dir, `${b}.json`), JSON.stringify(chapters));
    counts[b] ??= [];
    chapters.forEach((ch, c) => (counts[b][c] = Math.max(counts[b][c] ?? 0, ch.length)));
  });
  console.log(`wrote ${path.relative(process.cwd(), dir)}/ (66 books)`);
}

fs.writeFileSync(
  COUNTS_FILE,
  `// Generated by scripts/build-bibles.mjs — verses per chapter for each of the 66 books (longest of the bundled Bibles).\nexport const VERSE_COUNTS = ${JSON.stringify(counts)};\n`
);
console.log(`wrote ${path.relative(process.cwd(), COUNTS_FILE)}`);
